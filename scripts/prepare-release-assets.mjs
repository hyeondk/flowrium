import {spawn,execFileSync} from 'node:child_process';
import {createWriteStream} from 'node:fs';
import {mkdir,copyFile,readFile,writeFile,rm} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {pipeline} from 'node:stream/promises';
import {createGzip} from 'node:zlib';
import {fileURLToPath} from 'node:url';
import versions from '../electron/version.cjs';
const root=fileURLToPath(new URL('..',import.meta.url)),directory=resolve(process.argv[2]||'release');
const pkg=JSON.parse(await readFile(new URL('../package.json',import.meta.url),'utf8'));
const version=versions.releaseVersion(pkg);
const commit=execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim();
if(!/^[a-f0-9]{40}$/.test(commit))throw Error('소스 커밋을 확인하지 못했습니다.');
if(execFileSync('git',['status','--porcelain','--untracked-files=normal'],{cwd:root,encoding:'utf8'}).trim())throw Error('커밋한 소스만 릴리스로 묶을 수 있습니다. 변경 파일을 먼저 확인해 주세요.');
await mkdir(directory,{recursive:true});
for(const [source,name] of [['install.sh','install.sh'],['install.ps1','install.ps1'],['scripts/installer-support.cjs','flowrium-install-support.cjs']])await copyFile(join(root,source),join(directory,name));
const file=join(directory,`Flowrium-${version}-source.tar.gz`),temporary=file+'.tmp';
const child=spawn('git',['archive','--format=tar',`--prefix=Flowrium-${version}/`,commit],{cwd:root,stdio:['ignore','pipe','inherit']});
const completed=new Promise((resolve,reject)=>{child.once('error',reject);child.once('exit',code=>code===0?resolve():reject(Error('커밋 소스 묶음을 만들지 못했습니다.')))});
try{await Promise.all([pipeline(child.stdout,createGzip({level:9}),createWriteStream(temporary,{flags:'wx'})),completed]);await (await import('node:fs/promises')).rename(temporary,file)}finally{await rm(temporary,{force:true})}
await writeFile(join(directory,'SOURCE-COMMIT.txt'),`Flowrium ${version}\n${commit}\n`);
console.log(`커밋 ${commit.slice(0,12)} / 소스와 터미널 설치 파일 준비 완료`);
