const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises'),os=require('node:os'),path=require('node:path');
const {promisify}=require('node:util'),{execFile}=require('node:child_process'),{randomUUID}=require('node:crypto');
const cmd=promisify(execFile);
const {Store}=require('../electron/store.cjs');
const {prepareTeamWorktrees,registerTeamWorktrees,teamSessionDirectory}=require('../electron/team-worktrees.cjs');
const {Controller}=require('../electron/controller.cjs');
const {startWork}=require('../electron/workbench.cjs');
const git=async(dir,...args)=>(await cmd('git',['-C',dir,...args],{windowsHide:true})).stdout.trim();
async function setup(t) {
  const tmp=await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(),'flowrium-tree-'))),root=path.join(tmp,'내 프로젝트');
  const store=new Store(path.join(tmp,'profile'));
  await fs.mkdir(root); await store.load(); await git(root,'init','-b','main');
  await git(root,'config','user.name','격리 검증'); await git(root,'config','user.email','test@example.invalid');
  await fs.writeFile(path.join(root,'common.txt'),'initial\n');await fs.writeFile(path.join(root,'.gitignore'),'.flowrium/\nignored.tmp\n');
  await git(root,'add','.');await git(root,'commit','-m','기준');
  const project=await store.addProject(root), run=randomUUID(), api={};
  const controller=new Controller(store,{descriptor:{command:process.execPath,prefix:[path.join(__dirname,'backend-fake-codex.cjs')],node:true,label:'시험'}});
  registerTeamWorktrees((key,value)=>{api[key]=value;},store,controller);
  const roles=[{name:'기능',mode:'build'},{name:'수정',mode:'build'},{name:'검수',mode:'review',targetIndex:0}];
  const prepare=(indices)=>prepareTeamWorktrees(store,project.id,run,roles,{indices});
  const board=()=>api.teamWorktrees(project.id,run), action=(input)=>api.teamWorktreeAction(project.id,run,input);
  t.after(async()=>{await controller.shutdown();await fs.rm(tmp,{recursive:true,force:true,maxRetries:6,retryDelay:100});});
  return {tmp,root,store,controller,project,run,roles,prepare,board,action};
}
test('실제 역할별 작업 폴더 / 선택 커밋 / 충돌 보존·해결 / 작업 정리·재개',async(t)=>{
  const {root,prepare,board,action}=await setup(t);
  await prepare(); let b=await board();
  const a=b.roles[0],c=b.roles[1],qa=b.roles[2];
  assert.notEqual(a.directory,c.directory);assert.equal(qa.directory,a.directory);assert.equal(b.integration.directory,'');
  await fs.writeFile(path.join(a.directory,'common.txt'),'first\n');await fs.writeFile(path.join(c.directory,'common.txt'),'second\n');
  await fs.writeFile(path.join(a.directory,'keep.txt'),'preserve\n');
  assert.match(await action({action:'diff',index:0,file:'common.txt'}),/first/);
  assert.equal(await action({action:'diff',index:0,file:'keep.txt'}),'preserve\n');
  for(const [index,old] of [[0,a],[1,c]]) await action({action:'commit',index,head:old.head,files:['common.txt'],message:'역할 변경'});
  assert.equal(await git(a.directory,'ls-files','keep.txt'),'');
  await assert.rejects(action({action:'cleanup',index:0,head:(await board()).roles[0].head}),/변경/);
  await fs.unlink(path.join(a.directory,'keep.txt'));
  b=await board();
  await action({action:'integrate',index:0,head:b.roles[0].head,integrationHead:b.base});
  assert.match(await fs.readFile(path.join(root,'common.txt'),'utf8'),/initial/);
  b=await board();
  await assert.rejects(action({action:'integrate',index:1,head:b.roles[1].head,integrationHead:b.base}),/다시 확인/);
  assert.match(await action({action:'integrate',index:1,head:b.roles[1].head,integrationHead:b.integration.head}),/충돌/);
  b=await board();assert.deepEqual(b.integration.conflicts,['common.txt']);
  assert.ok(b.integration.mergeHead);assert.match(await fs.readFile(path.join(b.integration.directory,'common.txt'),'utf8'),/<<<<<<</);
  await assert.rejects(action({action:'finish',index:-1,head:b.integration.head}),/남은 충돌/);
  await action({action:'resolve',index:-1,head:b.integration.head,file:'common.txt',side:'theirs'});
  await action({action:'finish',index:-1,head:b.integration.head});
  b=await board();assert.equal(b.integration.mergeHead,'');assert.match(await fs.readFile(path.join(b.integration.directory,'common.txt'),'utf8'),/^second\r?\n$/);
  assert.equal(await git(root,'rev-parse','HEAD'),b.base);
  await fs.writeFile(path.join(c.directory,'ignored.tmp'),'preserve');
  await assert.rejects(action({action:'cleanup',index:1,head:b.roles[1].head}),/무시한 파일/);
  await fs.unlink(path.join(c.directory,'ignored.tmp'));
  await action({action:'cleanup',index:1,head:b.roles[1].head});
  assert.equal((await board()).roles[1].archived,true);
  await action({action:'restore',index:1});
  assert.equal((await board()).roles[1].head,b.roles[1].head);
  assert.match(await fs.readFile(path.join(c.directory,'common.txt'),'utf8'),/^second\r?\n$/);
});
test('사용자 선택 역할만 생성 / QA 쓰기 금지 / 실제 Codex RPC에 원래 폴더 대신 역할 폴더 전달',async(t)=>{
  const {store,controller,project,run,root,prepare,board,action}=await setup(t);
  await assert.rejects(board(),{code:'ENOENT'});await prepare([0,2]);const b=await board();
  assert.equal(b.roles[1].directory,'');
  const s=await startWork(store,{projectId:project.id,title:'구현',kind:'task'},{runId:run,index:0,mode:'build',isolated:true});
  const review=await startWork(store,{projectId:project.id,title:'검수',kind:'task'},{runId:run,index:2,mode:'review',isolated:true});
  assert.equal(await teamSessionDirectory(store,s,'build',controller),b.roles[0].directory);
  await assert.rejects(teamSessionDirectory(store,review,'build',controller),/읽기 전용/);
  await assert.rejects(action({action:'cleanup',index:2,head:b.roles[0].head}),/읽기 전용/);
  const captured=[];const original=controller.client.request.bind(controller.client);
  controller.client.request=async(method,input,...rest)=>{captured.push({method,input});return original(method,input,...rest);};
  const done=new Promise((resolve)=>{const fn=(e)=>{if(e.type==='done'&&e.sessionId===s.id){controller.off('event',fn);resolve(e);}};controller.on('event',fn);});
  await controller.send({sessionId:s.id,text:'검증해 주세요',mode:'build'});
  assert.equal((await done).status,'completed');
  assert.equal(captured.find(c=>c.method==='thread/start').input.cwd,b.roles[0].directory);
  const turn=captured.find(c=>c.method==='turn/start');assert.equal(turn.input.cwd,b.roles[0].directory);
  assert.deepEqual(turn.input.sandboxPolicy.writableRoots,[b.roles[0].directory]);assert.notEqual(turn.input.cwd,root);
});
