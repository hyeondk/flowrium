const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const {_electron} = require('playwright');
const {Store} = require('../electron/store.cjs');
const {trustFixtureProject, backendFixtureAccount} = require('./project-trust-fixture.cjs');
const {composer, openConversation} = require('./shell-test-helpers.cjs');

async function main() {
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'flowrium-chat-model-'));
  const profile = path.join(temp, 'profile');
  const env = {...process.env, FLOWRIUM_USER_DATA:profile, CODEX_HOME:path.join(temp, 'codex'), FLOWRIUM_TEST_CHAT_MODELS:'1', FLOWRIUM_TEST_CATALOG_FILE:path.join(temp,'new-model.fixture')};
  delete env.ELECTRON_RUN_AS_NODE;
  delete env.ELECTRON_RENDERER_URL;
  let app, page;
  const picker = () => page.getByRole('combobox', {name:'이 채팅의 모델', exact:true});
  const button = name => page.getByRole('button', {name, exact:true});
  const snapshot = () => page.evaluate(() => window.flowrium.bootstrap());
  async function launch() {
    app = await _electron.launch({args:[path.resolve(__dirname, '..')], env});
    page = await app.firstWindow();
    await page.setViewportSize({width:1280, height:900});
    page.setDefaultTimeout(10000);
    await button('개인 비서').waitFor();
  }
  const waitForChoice = value => page.waitForFunction(expected => {
    const picker = document.querySelector('.chat-model-picker');
    return picker && !picker.querySelector('[role=combobox]').disabled && picker.dataset.model === expected;
  }, value);
  async function choose(value) {
    await picker().click();
    const label={'catalog-preview':'추가된 시험 모델','gpt-6.1-sol':'GPT-6.1 Sol','gpt-6.1-terra':'GPT-6.1 Terra'}[value];
    const list=page.getByRole('listbox',{name:'이 채팅의 모델',exact:true});
    await list.getByRole('option',{name:label||/^기본 설정 따르기/,exact:Boolean(label)}).click();
    await waitForChoice(value);
    assert.equal(await page.getByRole('dialog', {name:'설정', exact:true}).count(), 0);
  }
  async function verifyTurn(id, model, effort) {
    const before = (await snapshot()).sessions.find(s => s.id === id).messages.length;
    await composer(page).fill('전송 모델 확인 ' + id);
    await button('작업 보내기').click();
    await page.waitForFunction(async ({id, before, expected}) => {
      const s = (await window.flowrium.bootstrap()).sessions.find(s => s.id === id);
      return s.messages.slice(before).some(m => m.role === 'assistant' && m.text === expected);
    }, {id, before, expected:`실제 전송 / ${model} / ${effort}`});
    await button('작업 보내기').waitFor();
  }
  async function verifyPerformanceSettings(id) {
    await page.locator('.settings-button').click();
    const settings=page.getByRole('dialog',{name:'설정',exact:true});
    await settings.getByRole('button',{name:'계정과 모델',exact:true}).click();
    const defaultSpeed=settings.getByRole('combobox',{name:'기본 실행 속도',exact:true});
    await defaultSpeed.selectOption('fast');
    await page.waitForFunction(async()=>(await window.flowrium.bootstrap()).settings.speed==='fast');
    await settings.getByRole('button',{name:'설정 닫기',exact:true}).click();
    await settings.waitFor({state:'detached'});
    const open=button('Reasoning and speed');
    await open.click();
    const controls=page.getByRole('group',{name:'Model controls',exact:true});
    await controls.waitFor();
    await page.waitForFunction(()=>{
      const popup=document.querySelector('.chat-performance-popup'), trigger=document.querySelector('.chat-performance-trigger');
      if(!popup?.matches(':popover-open')||!trigger)return false;
      const bounds=popup.getBoundingClientRect(),anchor=trigger.getBoundingClientRect();
      return getComputedStyle(popup).transform==='none'&&bounds.width>220&&bounds.left>=0&&bounds.right<=innerWidth&&bounds.bottom<=anchor.top;
    });
    const slider=controls.getByRole('slider',{name:'Reasoning effort',exact:true});
    const position=await controls.boundingBox();
    assert.equal(await slider.getAttribute('max'),'5');
    assert.equal(await slider.getAttribute('aria-valuetext'),'High');
    await slider.press('End');
    await page.waitForFunction(async id=>(await window.flowrium.bootstrap()).sessions.find(item=>item.id===id)?.preferences?.effort==='ultra',id);
    const moved=await controls.boundingBox();
    assert.ok(Math.abs(position.x-moved.x)<1&&Math.abs(position.y-moved.y)<1,'추론 선택으로 팝업이 움직이지 않습니다.');
    await page.waitForFunction(()=>document.querySelector('.chat-effort-slider').getAttribute('aria-disabled')==='false');
    const sliderBox=await slider.boundingBox();
    await slider.click({position:{x:sliderBox.width/2,y:sliderBox.height/2}});
    await page.waitForFunction(async id=>{
      const effort=(await window.flowrium.bootstrap()).sessions.find(item=>item.id===id)?.preferences?.effort;
      return effort==='high'||effort==='xhigh';
    },id);
    await controls.getByRole('button',{name:'Speed',exact:true}).click();
    const speed=controls.getByRole('group',{name:'Execution speed',exact:true});
    assert.equal(await speed.getByRole('button',{name:'Fast',exact:true}).getAttribute('aria-pressed'),'true');
    await speed.getByRole('button',{name:'Ultrafast',exact:true}).click();
    await page.waitForFunction(async id=>(await window.flowrium.bootstrap()).sessions.find(item=>item.id===id)?.preferences?.speed==='ultrafast',id);
    const state=await snapshot();
    assert.equal(state.settings.speed,'fast');
    assert.equal(state.sessions.find(item=>item.id!==id)?.preferences?.speed,undefined);
    await slider.press('Escape');
    await controls.waitFor({state:'hidden'});
    await composer(page).fill('속도 전송 확인');
    await button('작업 보내기').click();
    await page.waitForFunction(async id=>(await window.flowrium.bootstrap()).sessions.find(item=>item.id===id)?.messages.some(message=>message.text==='실제 실행 속도 / ultrafast'),id);
    await button('작업 보내기').waitFor();
    await open.click();
    await controls.getByRole('button',{name:'Speed',exact:true}).click();
    await speed.getByRole('button',{name:'Ultrafast',exact:true,pressed:true}).waitFor();
    const reset=controls.getByRole('button',{name:'기본값으로 복구',exact:true});
    await reset.hover();
    await controls.getByRole('tooltip',{name:'속도와 추론 수준을 계정 기본값으로 복구합니다'}).waitFor();
    await reset.click();
    await page.waitForFunction(async id=>{
      const settings=(await window.flowrium.bootstrap()).sessions.find(item=>item.id===id)?.preferences;
      return settings && !settings.effort && !settings.speed;
    },id);
    await speed.getByRole('button',{name:'Fast',exact:true,pressed:true}).waitFor();
    await slider.press('Escape');
    await controls.waitFor({state:'hidden'});
  }
  try {
    const store = new Store(profile);
    await store.load();
    const directory = path.join(temp, '프로젝트');
    await fs.mkdir(directory);
    const project = await store.addProject(directory);
    await trustFixtureProject(store, project, {account:backendFixtureAccount});
    const a = await store.createSession(project.id, {title:'첫 대화', preferences:{answerLength:'short',sandbox:'read-only'}});
    const b = await store.createSession(project.id, {title:'두 번째 대화'});
    await store.saveSettings({codexPath:path.join(__dirname,'backend-fake-codex.cjs'), model:'gpt-6.1-sol', effort:'high'});
    await launch();
    await openConversation(page, a.title);
    await waitForChoice('');
    assert.match(await page.locator('.chat-model-picker').getAttribute('title'), /기본 설정 따르기.*GPT-6.1 Sol/);
    await verifyPerformanceSettings(a.id);
    await fs.writeFile(env.FLOWRIUM_TEST_CATALOG_FILE,'합성 모델 출시');
    await picker().focus();
    await page.getByText('새 모델을 사용할 수 있습니다. 추가된 시험 모델',{exact:true}).waitFor();
    await picker().click();await page.getByRole('listbox',{name:'이 채팅의 모델',exact:true}).getByRole('option',{name:'추가된 시험 모델',exact:true}).waitFor();await picker().press('Escape');
    await choose('catalog-preview');
    await verifyTurn(a.id,'catalog-preview','high');
    assert.equal(await button('이 대화에서 프로젝트 편집 허용').count(),0);
    assert.equal(await page.getByLabel('작업 모드',{exact:true}).count(),0);
    assert.equal((await snapshot()).projects.find(row=>row.id===project.id).trustedForFileAccess,true);
    await composer(page).fill('대기검증');
    await button('작업 보내기').click();
    await button('작업 중지').waitFor();
    await page.waitForFunction(async sid => (await window.flowrium.bootstrap()).sessions.find(s=>s.id===sid).messages.at(-1)?.turnId,a.id);
    await composer(page).fill('현재 단계에 반영해 주세요');
    await composer(page).press('Enter');
    await page.waitForFunction(async sid => (await window.flowrium.bootstrap()).sessions.find(s=>s.id===sid).messages.some(m=>m.text==='추가 지시 반영 / 현재 단계에 반영해 주세요'),a.id);
    await button('작업 보내기').waitFor();
    const delivered=(await snapshot()).sessions.find(s=>s.id===a.id).messages.slice(-2);
    assert.deepEqual(delivered.map(m=>m.role),['user','assistant']);
    assert.equal(delivered[0].text,'현재 단계에 반영해 주세요');
    await choose('gpt-6.1-terra');
    await button('Reasoning and speed').click();
    const terraSpeed=page.getByRole('group',{name:'Model controls',exact:true});
    await terraSpeed.getByRole('button',{name:'Speed',exact:true}).click();
    assert.equal(await terraSpeed.getByRole('button',{name:'Ultrafast',exact:true}).isDisabled(),true);
    await button('Reasoning and speed').press('Escape');
    await terraSpeed.waitFor({state:'hidden'});
    await verifyTurn(a.id,'gpt-6.1-terra','low');
    let state = await snapshot();
    assert.equal(state.settings.model, 'gpt-6.1-sol');
    assert.equal(state.sessions.find(s=>s.id===a.id).preferences.answerLength, 'short');
    await openConversation(page, b.title);
    await waitForChoice('');
    await verifyTurn(b.id,'gpt-6.1-sol','high');
    await app.close();
    app = undefined;
    await launch();
    const title = (await snapshot()).sessions.find(s=>s.id===a.id).title;
    await openConversation(page, title);
    await waitForChoice('gpt-6.1-terra');
    await button('대화 관리').click();
    assert.equal(await page.getByLabel('이 대화의 모델',{exact:true}).inputValue(),'gpt-6.1-terra');
    await button('닫기').click();
    await composer(page).fill('대기검증');
    await button('작업 보내기').click();
    await button('작업 중지').waitFor();
    await choose('gpt-6.1-sol');
    await composer(page).fill('전송 모델 확인 / 대기열');
    await button('추가 지시 대기열에 넣기').click();
    await page.locator('.chat-queue-panel').getByText('전송 모델 확인 / 대기열', {exact:true}).waitFor();
    await choose('gpt-6.1-terra');
    await button('작업 중지').click();
    await page.waitForFunction(async id=>{
      const s=(await window.flowrium.bootstrap()).sessions.find(row=>row.id===id);
      return s.messages.at(-1)?.text==='실제 전송 / gpt-6.1-sol / high' && s.queuedMessages.some(q=>q.status==='sent');
    }, a.id);
    await choose('');
    await verifyTurn(a.id,'gpt-6.1-sol','high');
    await page.evaluate(()=>window.flowrium.saveSettings({model:''}));
    await page.reload();
    await button('개인 비서').waitFor();
    await openConversation(page, title);
    await waitForChoice('');
    await verifyTurn(a.id,'test-model','high');
    state = await snapshot();
    assert.equal(state.sessions.find(s=>s.id===a.id).preferences.model, undefined);
    assert.equal(state.sessions.find(s=>s.id===b.id).preferences?.model, undefined);
    await app.close();
    app=undefined;
    env.FLOWRIUM_TEST_PLAN='plus';
    await launch();
    await openConversation(page,title);
    await choose('gpt-6.1-sol');
    await page.waitForFunction(async ()=>(await window.flowrium.connectionStatus()).accountPlan==='plus');
    await button('Reasoning and speed').click();
    await button('Speed').click();
    const plusSpeed=page.getByRole('group',{name:'Execution speed',exact:true});
    assert.deepEqual(await plusSpeed.getByRole('button').allTextContents(),['Standard','Fast','Ultrafast']);
    assert.equal(await plusSpeed.getByRole('button',{name:'Fast',exact:true}).isEnabled(),true);
    assert.equal(await plusSpeed.getByRole('button',{name:'Ultrafast',exact:true}).isDisabled(),true);
    console.log('대화별 모델 화면 검사 통과 / 속도 기본값과 대화별 선택 / 여섯 단계 추론 슬라이더 / 두 대화 독립·전역 상속 / 재시작 / 전송과 대기열 모델·추론 강도 / 계정 기본값 복귀');
  } finally {
    if (app) await app.close();
    await fs.rm(temp, {recursive:true,force:true,maxRetries:6,retryDelay:100});
  }
}
main().catch(error => {console.error(error); process.exitCode=1;});
